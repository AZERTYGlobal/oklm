def _parse():
    starts, ends = [], []
    for item in "".join(_RANGES).split(","):
        low, _, high = item.partition("-")
        starts.append(int(low, 16))
        ends.append(int(high or low, 16))
    return starts, ends


_STARTS, _ENDS = _parse()


def needs_ldml_escape(ch):
    """True when `ch` (not the backslash) must be written as \\u{...} in an LDML output."""
    code = ord(ch)
    index = bisect.bisect_right(_STARTS, code) - 1
    return index >= 0 and code <= _ENDS[index]


